"""Sweep decision gates on independently labeled development evidence attempts.

Labels describe whether the retrieved passages suffice, not whether a gold
document was hit. This cannot estimate answers never generated by the model.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def calibrate(rows: list[dict], max_false_accept_rate: float = 0.05) -> dict:
    if not rows or not 0 <= max_false_accept_rate <= 1:
        raise ValueError("Need labeled rows and a false-accept rate between 0 and 1")
    ids = set()
    for row in rows:
        key = (row["question_id"], row.get("attempt", 0))
        if key in ids:
            raise ValueError("Duplicate question/attempt label")
        ids.add(key)
        if (
            type(row["evidence_sufficient"]) is not bool
            or type(row["model_sufficient"]) is not bool
        ):
            raise ValueError("Sufficiency labels must be booleans")
        for key in ("top_score", "grade_confidence"):
            if not isinstance(row[key], (int, float)) or not 0 <= row[key] <= 1:
                raise ValueError(f"Invalid {key}")
    positive = sum(row["evidence_sufficient"] for row in rows)
    negative = len(rows) - positive
    if not positive or not negative:
        raise ValueError("Calibration needs both sufficient and insufficient examples")
    results = []
    for score in sorted({0.0, 1.0, *(r["top_score"] for r in rows)}):
        for confidence in sorted({0.0, 1.0, *(r["grade_confidence"] for r in rows)}):
            accepted = [
                r
                for r in rows
                if r["model_sufficient"]
                and r["top_score"] >= score
                and r["grade_confidence"] >= confidence
            ]
            tp = sum(r["evidence_sufficient"] for r in accepted)
            fp = len(accepted) - tp
            results.append(
                {
                    "min_score": score,
                    "min_grade_confidence": confidence,
                    "true_accepts": tp,
                    "false_accepts": fp,
                    "recall": tp / positive,
                    "false_accept_rate": fp / negative,
                    "precision": tp / len(accepted) if accepted else None,
                }
            )
    feasible = [
        r
        for r in results
        if r["false_accept_rate"] <= max_false_accept_rate and r["true_accepts"]
    ]
    best = max(
        feasible,
        key=lambda r: (
            r["recall"],
            -r["false_accept_rate"],
            -r["min_score"],
            -r["min_grade_confidence"],
        ),
        default=None,
    )
    return {
        "rows": len(rows),
        "recommendation": best,
        "candidates": results,
        "model_rejected_sufficient": sum(
            r["evidence_sufficient"] and not r["model_sufficient"] for r in rows
        ),
        "note": "Development-set gate analysis only; never overrides model rejection. Validate on held-out questions before applying. No EM/F1 gain is implied.",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--labels", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--max-false-accept-rate", type=float, default=0.05)
    args = parser.parse_args()
    if args.output.resolve() == args.labels.resolve():
        raise ValueError("Output cannot overwrite labels")
    result = calibrate(json.loads(args.labels.read_text()), args.max_false_accept_rate)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2), encoding="utf-8")
    print(json.dumps({k: v for k, v in result.items() if k != "candidates"}, indent=2))


if __name__ == "__main__":
    main()
